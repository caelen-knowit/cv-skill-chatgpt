#!/usr/bin/env python3
"""
Deterministic build of the distributable files from cv-match-coach/:

  cv-match-coach.zip             – upload as a ChatGPT skill
  cv-match-coach-all-in-one.md   – the same skill as one text file (link / Project)
  CHECKSUMS.txt                  – SHA-256 of both (sha256sum format)
  README.md                      – checksum block between the checksum markers

The same skill files always give byte-identical outputs on any machine (fixed
timestamps, sorted order, no compression, version = content hash), so the
documented checksum can be reproduced by anyone.

Usage:  python3 tools/build.py          build and update files
        python3 tools/build.py --check  exit 1 if any output is out of date (CI)
"""
import hashlib
import io
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL = "cv-match-coach"
SKILL_DIR = ROOT / SKILL
ZIP_NAME = f"{SKILL}.zip"
AIO_NAME = f"{SKILL}-all-in-one.md"
REPO_RAW = "https://raw.githubusercontent.com/caelen-knowit/cv-skill-chatgpt/main"
JUNK = {".DS_Store", "Thumbs.db"}
FIXED_TIME = (1980, 1, 1, 0, 0, 0)


def skill_files():
    files = []
    for p in SKILL_DIR.rglob("*"):
        if p.is_file() and p.name not in JUNK and "__pycache__" not in p.parts:
            files.append(p)
    return sorted(files, key=lambda p: p.relative_to(ROOT).as_posix())


def read_bytes(p):
    data = p.read_bytes()
    # normalise line endings so Windows checkouts give the same result
    if p.suffix in {".md", ".py", ".txt"}:
        data = data.replace(b"\r\n", b"\n")
    return data


def version(files):
    h = hashlib.sha256()
    for p in files:
        h.update(p.relative_to(ROOT).as_posix().encode() + b"\0" + read_bytes(p) + b"\0")
    return h.hexdigest()[:12]


def build_zip(files):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_STORED) as z:
        for p in files:
            info = zipfile.ZipInfo(p.relative_to(ROOT).as_posix(), date_time=FIXED_TIME)
            info.external_attr = (0o644 & 0xFFFF) << 16
            info.create_system = 3  # unix, fixed for reproducibility
            z.writestr(info, read_bytes(p))
    return buf.getvalue()


def build_all_in_one(files, ver):
    parts = [
        f"# CV Match Coach – all-in-one (version {ver})",
        "",
        "This single file contains the complete CV Match Coach skill. Each part starts with a line '=== FILE: <path> ==='.",
        "Treat the part 'SKILL.md' as your instructions for this whole chat. When SKILL.md refers to a file such as",
        "'references/workflow.md', use the part with that path below. Read the whole file before starting.",
        f"The file ends with the line 'END-OF-CV-MATCH-COACH {ver}'.",
        "",
    ]
    order = lambda p: (0 if p.name == "SKILL.md" else 1 if "references" in p.parts else 2 if "examples" in p.parts else 3,
                       p.as_posix())
    for p in sorted(files, key=order):
        rel = p.relative_to(SKILL_DIR).as_posix()
        if not (rel == "SKILL.md" or rel.startswith("references/") or rel.startswith("scripts/")
                or (rel.startswith("examples/example-") and rel.endswith(".md"))):
            continue
        text = read_bytes(p).decode("utf-8")
        parts += [f"=== FILE: {rel} ===", ""]
        parts += (["```python", text.rstrip("\n"), "```"] if p.suffix == ".py" else [text.rstrip("\n")])
        parts.append("")
    parts.append(f"END-OF-CV-MATCH-COACH {ver}")
    return ("\n".join(parts) + "\n").encode("utf-8")


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def readme_block(zip_sha, aio_sha, ver):
    return f"""<!-- checksum:start (generated by tools/build.py – do not edit by hand) -->
**Verify the download (optional):** the SHA-256 checksum of `{ZIP_NAME}` (version `{ver}`) is
```
{zip_sha}
```
Check it with: **Windows (PowerShell)** `Get-FileHash .\\{ZIP_NAME}` · **Mac** `shasum -a 256 {ZIP_NAME}` · **Linux** `sha256sum {ZIP_NAME}`.
The result must match (upper/lower case doesn't matter). All checksums: [CHECKSUMS.txt](CHECKSUMS.txt).
<!-- checksum:end -->"""


def main():
    check = "--check" in sys.argv
    files = skill_files()
    ver = version(files)
    zip_bytes = build_zip(files)
    aio_bytes = build_all_in_one(files, ver)
    zip_sha, aio_sha = sha256(zip_bytes), sha256(aio_bytes)
    checksums = f"{zip_sha}  {ZIP_NAME}\n{aio_sha}  {AIO_NAME}\n".encode()

    readme_path = ROOT / "README.md"
    readme = readme_path.read_text(encoding="utf-8")
    pattern = re.compile(r"^([ \t]*)<!-- checksum:start.*?<!-- checksum:end -->", re.S | re.M)
    if not pattern.search(readme):
        sys.exit("README.md is missing the <!-- checksum:start --> ... <!-- checksum:end --> markers")
    new_readme = pattern.sub(
        lambda m: "\n".join(m.group(1) + line if line else line
                            for line in readme_block(zip_sha, aio_sha, ver).split("\n")),
        readme)

    outputs = {
        ROOT / ZIP_NAME: zip_bytes,
        ROOT / AIO_NAME: aio_bytes,
        ROOT / "CHECKSUMS.txt": checksums,
        readme_path: new_readme.encode("utf-8"),
    }
    stale = [p.name for p, data in outputs.items() if not p.exists() or p.read_bytes() != data]

    # public-repo guard: only markdown and the scripts belong in the published skill
    extra = [p.relative_to(ROOT).as_posix() for p in files
             if not (p.suffix == ".md" or (p.parent.name == "scripts" and p.suffix == ".py"))]

    if check:
        if stale:
            print("Out of date: " + ", ".join(stale) + ". Run: python3 tools/build.py")
            sys.exit(1)
        print(f"Up to date (version {ver}, zip sha256 {zip_sha})")
        return

    for p, data in outputs.items():
        if p.name in stale:
            p.write_bytes(data)
    print(f"Version {ver}")
    print(f"{zip_sha}  {ZIP_NAME}")
    print(f"{aio_sha}  {AIO_NAME}")
    print("Updated: " + (", ".join(stale) if stale else "nothing (already up to date)"))
    if extra:
        print("\nWARNING: the skill folder contains files other than markdown and scripts:")
        for e in extra:
            print("  " + e)
        print(f"Upload this zip to ChatGPT, but do NOT commit it to the public repo (git checkout -- {ZIP_NAME}).")


if __name__ == "__main__":
    main()
